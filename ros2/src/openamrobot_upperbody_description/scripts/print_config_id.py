#!/usr/bin/env python3
"""Print the configuration id of one expansion of combined_robot.xacro (ARCHITECTURE.md s7, ADR-010 as corrected by rev19.0).

    print_config_id.py column:=dold_v4_350 base_plate:=bp000 head_pitch:=hp25 base_tilt:=bt10 arm_package:=openarm
                       hardware_profile:=mock [enable_planar_base:=true] [datums_file:=PATH] [--upstream-commit SHA] [--explain]

Prints `sha256:` followed by 64 lowercase hex characters: the format of the openamrobot-interfaces C9 `sha256`
definition (`^sha256:[0-9a-f]{64}$`). A truncated id fails that validator, so this never prints one.

    id = "sha256:" + sha256(S).hexdigest()
    S  = UTF-8 of the JSON object (keys sorted, separators "," and ":", ASCII-escaped) with exactly these members:
           canonical_urdf              the xacro-expanded URDF, XML C14N 2.0 with comments dropped and whitespace-only
                                       text stripped (so the autogenerated banner, which names a path, does not count)
           column, base_plate, head_pitch, base_tilt     option B's four configuration IDs
           arm_package, hardware_profile
           datums_revision             `revision` of the datums file the expansion read
           upstream_pins               {name: full commit hash} for every entry of config/upstream_pins.yaml (the git
                                       checkout's HEAD when there is one, else the pin; a checkout with changes is an error)
    enable_planar_base is not a separate member: it changes the expanded URDF, so it is already in canonical_urdf.

What is NOT an input, on purpose: the lift stop (L1000 / L1175 / L1350). A stop is a joint position with a calibration, a
CALIBRATION ID, not a build variant; option B's own config says so and ADR-010 had it wrong. `mast_id` is gone with the mast.
The format is unchanged and so is validity against the C9 schema, while the meaning of the hash is not: an id recorded
before P15 (inputs: canonical_urdf, mast_id, arm_package, hardware_profile, datums_revision, openarm_description_commit)
is not comparable with one computed now, and nothing will fail to say so.

--explain also prints the inputs and a 12-character prefix, labelled as one, for human-facing logs.
"""
import argparse
import hashlib
import json
import os
import sys
import xml.etree.ElementTree as ET

import xacro
import yaml

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import evidence_common as ev  # noqa: E402

REQUIRED = ev.ROW_KEYS          # column base_plate head_pitch base_tilt arm_package hardware_profile
OPTIONAL = ("enable_planar_base", "datums_file")


def canonical_urdf(urdf_xml):
    return ET.canonicalize(urdf_xml, strip_text=True)


def config_id(urdf_xml, row, datums_revision, upstream_pins):
    """`row` is a dict with the six ROW_KEYS; `upstream_pins` is {name: commit} for every pin."""
    members = {
        "canonical_urdf": canonical_urdf(urdf_xml),
        **{key: row[key] for key in ev.ROW_KEYS},
        "datums_revision": datums_revision,
        "upstream_pins": dict(sorted(upstream_pins.items())),
    }
    payload = json.dumps(members, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("utf-8")
    return "sha256:" + hashlib.sha256(payload).hexdigest()


def datums_revision(datums_file):
    with open(datums_file) as f:
        return yaml.safe_load(f)["revision"]


def config_id_of(share, upstream_pins, row, enable_planar_base="false", datums_file=None):
    """Expand and hash in one go. `datums_file` defaults to the package's, which is also where the revision is read.
    `upstream_pins` is {name: commit} (see `pins_of`); `row` has the six ROW_KEYS."""
    datums_file = datums_file or os.path.join(share, "config", "datums.yaml")
    urdf = ev.expand_urdf(share, row, enable_planar_base, datums_file)
    return config_id(urdf, row, datums_revision(datums_file), upstream_pins)


def pins_of(workspace, pins_file=None):
    """({name: commit}, {name: where it came from}) for every pin of upstream_pins.yaml: the checkout's HEAD where one exists."""
    pins, sources = {}, {}
    for name in ev.all_pins(pins_file):
        pins[name], sources[name] = ev.upstream_commit_and_source(workspace, name, pins_file)
    return pins, sources


def _parse(argv):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0],
                                     usage="%(prog)s column:=ID base_plate:=ID head_pitch:=ID base_tilt:=ID arm_package:=PKG "
                                           "hardware_profile:=PROFILE [...]")
    parser.add_argument("args", nargs="+", metavar="key:=value")
    parser.add_argument("--upstream-commit", default=None,
                        help="override the openarm_description commit (default: HEAD of <workspace>/src/upstream/openarm_description, "
                             "else its pin); every other pin is read as usual")
    parser.add_argument("--explain", action="store_true", help="also print the inputs and a labelled 12-character prefix")
    ns = parser.parse_args(argv)
    values = {}
    for item in ns.args:
        key, sep, value = item.partition(":=")
        if not sep or key not in REQUIRED + OPTIONAL:
            parser.error(f"unrecognised argument {item!r}; expected one of {', '.join(k + ':=...' for k in REQUIRED + OPTIONAL)}")
        values[key] = value
    missing = [k for k in REQUIRED if k not in values]
    if missing:
        parser.error("missing: " + ", ".join(k + ":=..." for k in missing))
    return ns, values


def main(argv=None):
    ns, values = _parse(argv)
    try:
        share = ev.share_dir()
        pins, sources = pins_of(ev.workspace_root(share))
        if ns.upstream_commit:
            pins["openarm_description"], sources["openarm_description"] = ns.upstream_commit, "--upstream-commit"
        row = {k: values[k] for k in REQUIRED}
        cid = config_id_of(share, pins, row, values.get("enable_planar_base", "false"), values.get("datums_file"))
    except ev.EvidenceError as err:
        print(f"print_config_id: {err}", file=sys.stderr)
        return 2
    except xacro.XacroException as err:
        print(f"print_config_id: xacro failed: {err}", file=sys.stderr)
        return 2
    print(cid)
    if ns.explain:
        hexdigest = cid.split(":", 1)[1]
        print(f"  prefix (12 hex, for log lines only, not an id): {hexdigest[:12]}", file=sys.stderr)
        for key in REQUIRED + OPTIONAL:
            if key in values:
                print(f"  {key} = {values[key]}", file=sys.stderr)
        for name, commit in sorted(pins.items()):
            print(f"  upstream_pins.{name} = {commit}  (from {sources[name]})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
