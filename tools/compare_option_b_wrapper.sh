#!/usr/bin/env bash
# compare_option_b_wrapper.sh [REV_A [REV_B]] : expand option B's standalone wrapper (openamrobot_upperbody.xacro) with its defaults at two git
# revisions and compare the URDFs byte for byte, after removing the one line xacro writes with the input file's path.
# Defaults: REV_A=upstream/main, REV_B=HEAD. Needs ROS (xacro) sourced and both revisions in this checkout.
# Prints the diff (empty = byte-identical) and exits 0 when the only differences are the ones listed in EXPECTED below, 1 otherwise.
# What it says about the claim in the PR body: with emit_arm_mounts and column_inertial at their defaults, the wrapper expands as on main.
set -eu
A=${1:-upstream/main}; B=${2:-HEAD}
PKG=ros2/src/openamrobot_upperbody_description
REPO=$(git rev-parse --show-toplevel); cd "$REPO"
WORK=$(mktemp -d); trap 'rm -rf "$WORK"' EXIT
expand() {   # $1 rev, $2 output
  local d=$WORK/$(echo "$1" | tr / _)
  mkdir -p "$d/prefix/share/ament_index/resource_index/packages"
  git archive "$1" "$PKG" | tar -x -C "$d"
  mv "$d/$PKG" "$d/prefix/share/openamrobot_upperbody_description"
  touch "$d/prefix/share/ament_index/resource_index/packages/openamrobot_upperbody_description"
  cat > "$d/drv.xacro" <<XML
<?xml version="1.0"?>
<robot xmlns:xacro="http://www.ros.org/wiki/xacro" name="wrapper_check">
  <xacro:include filename="\$(find openamrobot_upperbody_description)/urdf/openamrobot_upperbody.xacro"/>
  <link name="base_link"/>
  <xacro:openamrobot_upperbody parent="base_link" column="dold_v4_350" base_plate="bp000" head_pitch="hp25" base_tilt="bt10" column_axis_x_bp000="0.060"/>
</robot>
XML
  AMENT_PREFIX_PATH="$d/prefix:${AMENT_PREFIX_PATH:-}" xacro "$d/drv.xacro" | grep -v "autogenerated by xacro from" > "$2"
}
expand "$A" "$WORK/a.urdf"; expand "$B" "$WORK/b.urdf"
if diff -u "$WORK/a.urdf" "$WORK/b.urdf" > "$WORK/d.diff"; then echo "byte-identical (after the xacro path comment): $A vs $B"; exit 0; fi
cat "$WORK/d.diff"
# the one difference accepted: an empty lift_column_base_link as an open/close pair instead of a self-closing tag
python3 - "$WORK/a.urdf" "$WORK/b.urdf" <<'PY'
import re, sys
norm = lambda p: re.sub(r'<link name="lift_column_base_link">\s*</link>', '<link name="lift_column_base_link"/>', open(p).read())
sys.exit(0 if norm(sys.argv[1]) == norm(sys.argv[2]) else 1)
PY
rc=$?; [ $rc -eq 0 ] && echo "the only difference is the empty lift_column_base_link serialised as <link ...></link>" || echo "DIFFERENT beyond the serialisation of the empty link"
exit $rc
